def _build_zip_base64(
    audit_id: str,
    target: str,
    scorecard: Dict[str, Any],
    unified_diff: str,
    middleware_py: str,
    middleware_ts: str,
    pr_md: str,
) -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("patch.diff", unified_diff)
        zf.writestr("guard402_middleware.py", middleware_py)
        zf.writestr("guard402_middleware.ts", middleware_ts)
        zf.writestr("PR_DESCRIPTION.md", pr_md)
        zf.writestr("SECURITY_SCORECARD.json", json.dumps(scorecard, indent=2))
        zf.writestr(
            "APPLY_INSTRUCTIONS.md",
            f"# Guard402 AutoPatch Bundle (`{audit_id}`)\n\n"
            f"Target: `{target}`\n\n"
            f"## 1. Apply the Unified Diff\n```bash\ngit apply patch.diff\n```\n\n"
            f"## 2. Drop-In Hardened Middleware\n"
            f"- For Python / FastAPI / Starlette MCP servers: copy `guard402_middleware.py` into your source root.\n"
            f"- For TypeScript / Node MCP servers: copy `guard402_middleware.ts` into `src/`.\n",
        )
    return base64.b64encode(buf.getvalue()).decode("utf-8")


